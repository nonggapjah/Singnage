using System;
using System.IO;
using System.Linq;
using System.Security.Cryptography;
using System.Text;
using System.Threading.Tasks;
using Xabe.FFmpeg;

namespace MassConvertMedia
{
    // One-off bulk re-encoder for files already published under wwwroot/media.
    //
    // F33: the previous version overwrote each file IN PLACE and deleted the original first. The
    // database row kept the old file_hash and file_size_kb, so every screen that validated the
    // download against the stored hash rejected the converted file -- forever -- and the only copy
    // that matched the row was gone. Now:
    //   - the original is MOVED to <media>/_originals/ (never deleted);
    //   - the converted file replaces it under the same name (clients key the cache by that name);
    //   - the new MD5 + size are printed and written to update_hashes.sql next to the media folder,
    //     which the operator applies to sn_media_files so rows and bytes agree again.
    // Usage: MassConvertMedia [mediaFolder] [ffmpegFolder]
    class Program
    {
        static async Task Main(string[] args)
        {
            try
            {
                string mediaPath = args.Length > 0 ? args[0] : @"c:\git\Signage-Unicorn\src\SignageUnicorn.Api\wwwroot\media";
                string ffmpegPath = args.Length > 1 ? args[1] : @"c:\git\Signage-Unicorn\src\SignageUnicorn.Api\ffmpeg";

                if (!Directory.Exists(mediaPath))
                {
                    Console.WriteLine($"Media folder not found: {mediaPath}");
                    return;
                }

                FFmpeg.SetExecutablesPath(ffmpegPath);

                string originalsPath = Path.Combine(mediaPath, "_originals");
                Directory.CreateDirectory(originalsPath);

                string sqlScriptPath = Path.Combine(Path.GetDirectoryName(Path.GetFullPath(mediaPath)) ?? mediaPath, "update_hashes.sql");
                var sql = new StringBuilder();
                sql.AppendLine("-- Generated by MassConvertMedia on " + DateTime.UtcNow.ToString("u"));
                sql.AppendLine("-- Review, then run against SignageUnicornDB so sn_media_files matches the re-encoded files.");
                sql.AppendLine("-- Screens re-download a file when its hash changes (FORCE_SYNC or next schedule sync).");
                sql.AppendLine();

                var files = Directory.GetFiles(mediaPath, "*.mp4")
                            .Concat(Directory.GetFiles(mediaPath, "*.mov"))
                            .Concat(Directory.GetFiles(mediaPath, "*.webm"))
                            .ToList();

                Console.WriteLine($"Found {files.Count} files to check in: {mediaPath}");
                Console.WriteLine($"Originals will be kept in: {originalsPath}");

                int converted = 0;
                foreach (var file in files)
                {
                    try
                    {
                        string fileName = Path.GetFileName(file);
                        if (fileName.Contains(".fixed.mp4")) continue;

                        Console.WriteLine($"\n[ {DateTime.Now.ToLongTimeString()} ] Processing: {fileName}");
                        var mediaInfo = await FFmpeg.GetMediaInfo(file);
                        var videoStream = mediaInfo.VideoStreams.FirstOrDefault();

                        if (videoStream == null)
                        {
                            Console.WriteLine("  Skipping: No video stream found.");
                            continue;
                        }

                        string outputPath = file + ".fixed.mp4";
                        if (File.Exists(outputPath)) File.Delete(outputPath);

                        // Same target as the API's own transcoder: High@4.0 covers 1080p honestly;
                        // Baseline@3.0 produced streams whose declared level contradicted their
                        // contents and made hardware decoders fail mid-play.
                        Console.WriteLine("  Converting to H.264 High@4.0 ...");

                        var conversion = FFmpeg.Conversions.New()
                            .AddStream(videoStream.SetCodec(VideoCodec.h264))
                            .AddParameter("-profile:v high -level 4.0 -pix_fmt yuv420p -movflags +faststart");

                        var audioStream = mediaInfo.AudioStreams.FirstOrDefault();
                        if (audioStream != null)
                        {
                            conversion.AddStream(audioStream.SetCodec(AudioCodec.aac).SetBitrate(128000));
                        }

                        conversion.SetOutput(outputPath);
                        await conversion.Start();

                        if (!File.Exists(outputPath) || new FileInfo(outputPath).Length == 0)
                        {
                            Console.WriteLine("  ERROR: conversion produced no output; original left untouched.");
                            continue;
                        }

                        // Keep the original (recovery copy), then put the converted file under the
                        // published name.
                        string backupPath = Path.Combine(originalsPath, fileName);
                        if (File.Exists(backupPath)) backupPath = Path.Combine(originalsPath, $"{Path.GetFileNameWithoutExtension(fileName)}_{DateTime.UtcNow:yyyyMMddHHmmss}{Path.GetExtension(fileName)}");
                        File.Move(file, backupPath);
                        File.Move(outputPath, file);

                        string md5 = ComputeMd5(file);
                        long sizeKb = new FileInfo(file).Length / 1024;
                        converted++;

                        Console.WriteLine($"  SUCCESS: {fileName}  md5={md5}  size={sizeKb} KB  (original -> {Path.GetFileName(backupPath)})");
                        sql.AppendLine($"UPDATE sn_media_files SET file_hash = '{md5}', file_size_kb = {sizeKb}, updated_at = SYSUTCDATETIME() WHERE blob_url LIKE '%/{fileName.Replace("'", "''")}';");
                    }
                    catch (Exception ex)
                    {
                        Console.WriteLine($"  ERROR processing {file}: {ex.Message}");
                    }
                }

                File.WriteAllText(sqlScriptPath, sql.ToString());
                Console.WriteLine($"\nMass Refresh Completed! {converted} file(s) converted.");
                Console.WriteLine($"Hash/size updates written to: {sqlScriptPath}");
                Console.WriteLine("Apply that script to the database, then send FORCE_SYNC to the affected screens.");
            }
            catch (Exception ex)
            {
                Console.WriteLine($"Fatal Error: {ex}");
            }
        }

        static string ComputeMd5(string path)
        {
            using var md5 = MD5.Create();
            using var stream = File.OpenRead(path);
            return BitConverter.ToString(md5.ComputeHash(stream)).Replace("-", "").ToLowerInvariant();
        }
    }
}
