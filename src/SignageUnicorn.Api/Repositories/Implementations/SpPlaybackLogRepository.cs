using Dapper;
using Microsoft.Data.SqlClient;
using SignageUnicorn.Api.Models; // For DTOs
using SignageUnicorn.Api.Repositories.Interfaces;
using System.Data;

namespace SignageUnicorn.Api.Repositories.Implementations
{
    public class SpPlaybackLogRepository : IPlaybackLogRepository
    {
        private readonly string _connectionString;

        public SpPlaybackLogRepository(IConfiguration configuration)
        {
            _connectionString = configuration.GetConnectionString("DefaultConnection")
                                ?? throw new InvalidOperationException("Connection string 'DefaultConnection' not found.");
            Dapper.DefaultTypeMap.MatchNamesWithUnderscores = true;
        }

        private IDbConnection CreateConnection() => new SqlConnection(_connectionString);

        private class SpStdResult
        {
            public int err_code { get; set; }
            public bool err_flag { get; set; }
            public string msg { get; set; }
        }

        private static DynamicParameters BuildInsertParameters(CreatePlaybackLogRequest log)
        {
            var p = new DynamicParameters();
            p.Add("@p_action", "INSERT");
            p.Add("@p_duration_sec", log.Duration);
            p.Add("@p_status", log.Result ?? "success");
            p.Add("@p_error_message", log.ErrorMessage);
            // Contract item 4: idempotency key generated by the client (null for legacy clients).
            p.Add("@p_event_uuid", string.IsNullOrWhiteSpace(log.EventId) ? null : log.EventId.Trim());

            if (long.TryParse(log.DeviceId, out var devId)) p.Add("@p_device_id", devId);
            else p.Add("@p_device_uuid", log.DeviceId);

            if (long.TryParse(log.MediaId, out var mediaId)) p.Add("@p_media_id", mediaId);
            else p.Add("@p_media_uuid", log.MediaId);

            if (long.TryParse(log.PlaylistId, out var plId)) p.Add("@p_playlist_id", plId);
            else p.Add("@p_playlist_uuid", log.PlaylistId);

            // The client sends UTC (ISO-8601 "Z"); the procedure no longer shifts it.
            p.Add("@p_start_time", log.PlayedAt);
            return p;
        }

        // Contract T6: is this event-less batch from a deployed v2.7.x client? Such a client cannot
        // read per-event results and deletes the whole batch on HTTP 200, so the batch must be stored
        // all-or-nothing.
        internal static bool IsLegacyBatch(IEnumerable<CreatePlaybackLogRequest> logs)
            => logs.All(l => string.IsNullOrWhiteSpace(l.EventId));

        private static async Task OpenAsync(IDbConnection db)
        {
            try
            {
                if (db is SqlConnection sqlConn) await sqlConn.OpenAsync(); else db.Open();
            }
            catch (Exception ex)
            {
                // Cannot even reach the database: by definition retryable.
                throw new RetryableStoreException($"Database unavailable: {ex.Message}", ex);
            }
        }

        // Runs one INSERT on an already-open connection and translates the procedure's two result
        // sets (status contract, then outcome) into an explicit result. F28: the old code discarded
        // err_flag entirely, so "Device or Media not found" still looked like success to the client,
        // which then deleted its only copy of the event.
        private static async Task<PlaybackIngestResult> InsertOneAsync(IDbConnection db, CreatePlaybackLogRequest log, IDbTransaction? transaction = null)
        {
            using var multi = await db.QueryMultipleAsync("sp_playback_log_std", BuildInsertParameters(log), transaction, commandType: CommandType.StoredProcedure);
            var status = await multi.ReadFirstOrDefaultAsync<SpStdResult>();
            if (status == null) return new PlaybackIngestResult { Accepted = false, Error = "no status returned" };
            if (status.err_flag)
            {
                // The procedure catches its own INSERT errors and reports the SQL error number. R4: only
                // a validation outcome (4xx: unknown device/media, bad data) or a data error is a
                // rejection the client may delete; everything else (transient, schema mismatch, an old
                // procedure answering "Unknown action") is a retry.
                if (SqlTransientErrors.IsProcedureValidationCode(status.err_code))
                    return new PlaybackIngestResult { Accepted = false, Error = status.msg ?? "DB error" };
                throw new RetryableStoreException($"SQL {status.err_code}: {status.msg}");
            }

            string? outcome = null;
            if (!multi.IsConsumed)
            {
                try { outcome = await multi.ReadFirstOrDefaultAsync<string>(); } catch { outcome = null; }
            }
            var duplicate = string.Equals(outcome, "duplicate", StringComparison.OrdinalIgnoreCase)
                            || (status.msg ?? string.Empty).StartsWith("Duplicate", StringComparison.OrdinalIgnoreCase);
            return new PlaybackIngestResult { Accepted = true, Duplicate = duplicate };
        }

        public async Task<PlaybackIngestResult> LogPlaybackAsync(CreatePlaybackLogRequest log)
        {
            using var db = CreateConnection();
            await OpenAsync(db);
            try
            {
                return await InsertOneAsync(db, log);
            }
            catch (SqlException ex) when (ex.Number == 2601 || ex.Number == 2627)
            {
                return new PlaybackIngestResult { Accepted = true, Duplicate = true };
            }
            catch (SqlException ex) when (SqlTransientErrors.IsDataError(ex))
            {
                return new PlaybackIngestResult { Accepted = false, Error = $"SQL {ex.Number}: {ex.Message}" };
            }
            catch (Exception ex) when (ex is not RetryableStoreException)
            {
                // R4: anything that is not a known data error is a store failure -> retry later.
                throw new RetryableStoreException($"Database error: {ex.Message}", ex);
            }
        }

        // Contract T6 / Codex round-2 findings 10 and 11.
        //   - Transient failures (connection lost, timeout, deadlock, failover) surface as
        //     RetryableStoreException -> HTTP 503; the client keeps its events and re-sends them. The
        //     events already stored before the failure are safe to re-send: the event id makes the
        //     insert idempotent.
        //   - Only the procedure's own validation outcomes (unknown device/media, bad data) are
        //     reported as rejected, which is what a client may delete.
        //   - A batch without event ids comes from a deployed v2.7.x client that deletes everything on
        //     HTTP 200: it is stored in one transaction and any failure stores NOTHING (503 or 400).
        public async Task<PlaybackBatchResult> LogPlaybackBatchAsync(IEnumerable<CreatePlaybackLogRequest> logs)
        {
            var result = new PlaybackBatchResult();
            var list = logs?.ToList() ?? new List<CreatePlaybackLogRequest>();
            if (list.Count == 0) return result;

            using var db = CreateConnection();
            await OpenAsync(db);

            if (IsLegacyBatch(list))
            {
                await StoreLegacyBatchAsync(db, list, result);
                return result;
            }

            foreach (var log in list)
            {
                try
                {
                    var one = await InsertOneAsync(db, log);
                    if (one.Accepted) result.Accepted.Add(log.EventId ?? string.Empty);
                    else result.Rejected.Add(new PlaybackRejectedEvent { EventId = log.EventId, Reason = one.Error ?? "rejected" });
                }
                catch (SqlException ex) when (ex.Number == 2601 || ex.Number == 2627)
                {
                    // Unique index on event_uuid fired: a concurrent upload already stored this event.
                    // That IS the idempotency contract working, so the client may delete its copy.
                    result.Accepted.Add(log.EventId ?? string.Empty);
                }
                catch (RetryableStoreException)
                {
                    throw;
                }
                catch (SqlException ex) when (SqlTransientErrors.IsDataError(ex))
                {
                    // A data error is about this event (a constraint, a bad value): rejected.
                    result.Rejected.Add(new PlaybackRejectedEvent { EventId = log.EventId, Reason = $"SQL {ex.Number}: {ex.Message}" });
                }
                catch (Exception ex)
                {
                    // R4: everything else (transient, schema, missing procedure) is a store failure.
                    throw new RetryableStoreException($"Database error: {ex.Message}", ex);
                }
            }
            return result;
        }

        private static async Task StoreLegacyBatchAsync(IDbConnection db, List<CreatePlaybackLogRequest> list, PlaybackBatchResult result)
        {
            using var transaction = db.BeginTransaction();
            try
            {
                foreach (var log in list)
                {
                    var one = await InsertOneAsync(db, log, transaction);
                    if (!one.Accepted)
                    {
                        transaction.Rollback();
                        throw new PlaybackBatchValidationException(one.Error ?? "Playback log rejected");
                    }
                }
                transaction.Commit();
                // Legacy clients only read "count"; the ids are empty strings by construction.
                foreach (var log in list) result.Accepted.Add(log.EventId ?? string.Empty);
            }
            catch (PlaybackBatchValidationException)
            {
                throw;
            }
            catch (RetryableStoreException)
            {
                TryRollback(transaction);
                throw;
            }
            catch (Exception ex)
            {
                TryRollback(transaction);
                // R4: a legacy batch is refused for good only on a data error; anything else is retried.
                if (SqlTransientErrors.IsDataError(ex)) throw new PlaybackBatchValidationException($"Batch rejected: {ex.Message}");
                throw new RetryableStoreException($"Database error: {ex.Message}", ex);
            }
        }

        private static void TryRollback(IDbTransaction transaction)
        {
            try { transaction.Rollback(); } catch { /* already rolled back or connection gone */ }
        }

        public async Task<IEnumerable<PlaybackLogDto>> GetLatestLogsAsync(int top)
        {
            using var db = CreateConnection();
            var p = new DynamicParameters();
            p.Add("@p_action", "GET_LATEST");
            p.Add("@p_top", top);

            // 1. Status 2. Data
            using var multi = await db.QueryMultipleAsync("sp_playback_log_std", p, commandType: CommandType.StoredProcedure);
            var status = await multi.ReadFirstOrDefaultAsync<SpStdResult>();
            if (status != null && status.err_flag) return Enumerable.Empty<PlaybackLogDto>();

            return await multi.ReadAsync<PlaybackLogDto>();
        }

        public async Task<IEnumerable<PlaybackLogDto>> GetLogsByDeviceAsync(string deviceId, int top)
        {
            using var db = CreateConnection();
            var p = new DynamicParameters();
            p.Add("@p_action", "GET_BY_DEVICE");
            p.Add("@p_top", top);

            if (long.TryParse(deviceId, out var devId)) p.Add("@p_device_id", devId);
            else p.Add("@p_device_uuid", deviceId);

            using var multi = await db.QueryMultipleAsync("sp_playback_log_std", p, commandType: CommandType.StoredProcedure);
            var status = await multi.ReadFirstOrDefaultAsync<SpStdResult>();
            if (status != null && status.err_flag) return Enumerable.Empty<PlaybackLogDto>();

            return await multi.ReadAsync<PlaybackLogDto>();
        }

